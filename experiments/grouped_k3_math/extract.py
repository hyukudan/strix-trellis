"""Mechanical extraction of our pinned baseline only; never reads upstream code."""
from pathlib import Path
import sys
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'tools'))
import verify_grouped_k3_adapter as contract


def literal_body(text, name):
    # The selected bodies contain no brace literals. Confirm token identity below.
    start = text.index('{', text.index(name + '('))
    depth = 1
    end = start + 1
    while depth:
        depth += (text[end] == '{') - (text[end] == '}')
        end += 1
    result = text[start + 1:end - 1]
    assert contract.tokens(result) == contract.body(text, name)
    return result


def generate():
    out = '''// PRIVATE source/build candidate. No production entry point.
// Generated by extract.py from this repository's pinned independent baseline.
#include "abi.hpp"
#include "../../src/hadamard.hpp"
#include "../../src/trellis_optimized.hpp"
#include "../../src/packed_decoder.hpp"
#include <type_traits>
namespace strix_trellis {
using grouped_k3_math::NativeBatch;
'''
    for stage, (path, old, new) in contract.SOURCES.items():
        original = (ROOT / path).read_text(encoding='utf-8')
        out += '\n__global__ __launch_bounds__(128) void ' + new + '(NativeBatch b) {\n'
        out += contract.PROLOGUES[stage] + '\n' + literal_body(original, old) + '\n}\n'
    out += '} // namespace strix_trellis\n'
    return out


def views():
    source = (ROOT / 'src/api.hip').read_text(encoding='utf-8')
    begin = source.index('struct strix_context_impl {')
    end = source.index('\nnamespace {', begin)
    result = ('// Literal current pinned V13 private views; not public ABI.\n#pragma once\n'
            '#include "../../include/strix_trellis.h"\n#include "../../src/backend.hpp"\n' +
            source[begin:end] + '\nstatic_assert(sizeof(strix_trellis::DeviceWeights)==56);\n'
            'static_assert(offsetof(strix_trellis::DeviceWeights,fused_output_capable)==48);\n')
    for name, offset in [('trellis',0),('suh',8),('svh',16),('bias',24),('input',32),
                         ('output',36),('bits',40),('codebook',44)]:
        result += f'static_assert(offsetof(strix_trellis::DeviceWeights,{name})=={offset});\n'
    return result


if __name__ == '__main__':
    target = Path(__file__).with_name('kernels.hip')
    result = generate()
    if '--check' in sys.argv:
        assert target.read_text(encoding='utf-8') == result
        assert target.with_name('private_views.hpp').read_text(encoding='utf-8') == views()
        print('PASS deterministic literal extraction')
    else:
        target.write_text(result, encoding='utf-8', newline='\n')
        target.with_name('private_views.hpp').write_text(views(), encoding='utf-8', newline='\n')
